#!/usr/bin/env python3
"""
Iskut coast generator.
Run from the project root:   python tools/gen_coast.py
 - rebuilds data/structures/beach_transition.vstruct (rounded coast, smooth ramp, wading shallows)
 - removes the 83 scattered rock_* cuboids from plaza.vstruct
 - turns the 3 dark stone dock decks into wood planks, flush with the sand
Needs: python3, numpy, scipy.   A backup (.bak) of plaza.vstruct is written once.
"""
import re, shutil, sys
from pathlib import Path
import numpy as np
from scipy.ndimage import distance_transform_edt, gaussian_filter

ROOT = Path(__file__).resolve().parent
while not (ROOT / "data" / "structures").exists() and ROOT.parent != ROOT:
    ROOT = ROOT.parent
S = ROOT / "data" / "structures"
PLAZA, BEACH = S / "plaza.vstruct", S / "beach_transition.vstruct"

# ---- tunables -------------------------------------------------------------
CELL = 1.0            # grid size in blocks
SMOOTH_SIGMA = 2.2    # bigger = rounder coastline
BANDS = [             # (max distance from grass edge, material, top Y, solid)
    (2.0, "sand",     0.000, True),    # dry sand, flush with the dirt/grass top (no lip)
    (3.5, "sand",    -0.050, True),    # mid beach
    (5.0, "wet_sand",-0.120, True),    # wet sand, just above the sea (-0.18)
    (8.0, "wet_sand",-0.500, True),    # hidden wading floor under the water
]
SEA_TOP, FOAM_AT = -0.18, 7.0
BOTTOM = -1.0         # underside of every beach block
# ---------------------------------------------------------------------------

# 1) land mask from the foundation rects in plaza.vstruct
txt = PLAZA.read_text()
found = [tuple(map(float, m.groups())) for m in re.finditer(
    r"^CUBOID foundation_\d+ dirt (\S+) \S+ (\S+) (\S+) \S+ (\S+)", txt, re.M)]
x0 = min(x - w / 2 for x, z, w, d in found) - 16
x1 = max(x + w / 2 for x, z, w, d in found) + 16
z0 = min(z - d / 2 for x, z, w, d in found) - 16
z1 = max(z + d / 2 for x, z, w, d in found) + 16
nx, nz = int((x1 - x0) / CELL), int((z1 - z0) / CELL)
cx = x0 + (np.arange(nx) + .5) * CELL
cz = z0 + (np.arange(nz) + .5) * CELL
X, Z = np.meshgrid(cx, cz)
land = np.zeros((nz, nx), bool)
for x, z, w, d in found:
    land |= (abs(X - x) < w / 2) & (abs(Z - z) < d / 2)

# 2) rounded grass mask (corners shaved, never bigger than the real foundation)
grass = (gaussian_filter(land.astype(float), SMOOTH_SIGMA) > 0.5) & land

# 3) dock decks (beach cells under them are skipped)
decks = [tuple(map(float, m.groups())) for m in re.finditer(
    r"^CUBOID dock_\w+_deck \S+ (\S+) \S+ (\S+) (\S+) \S+ (\S+)", txt, re.M)]
under_dock = np.zeros_like(land)
for x, z, w, d in decks:
    under_dock |= (abs(X - x) < w / 2 + .01) & (abs(Z - z) < d / 2 + .01)

dist = distance_transform_edt(~grass) * CELL   # distance to nearest grass cell
band = np.full(land.shape, -1)
for i, (maxd, *_ ) in enumerate(BANDS):
    band[(band < 0) & (dist <= maxd) & ~land] = i
band[under_dock & (band >= 0)] = -2             # covered by a pier

def rects(mask):
    """greedy merge of True cells into rectangles -> (ix0, iz0, w, d)"""
    m, out = mask.copy(), []
    for j in range(m.shape[0]):
        i = 0
        while i < m.shape[1]:
            if not m[j, i]: i += 1; continue
            w = 1
            while i + w < m.shape[1] and m[j, i + w]: w += 1
            d = 1
            while j + d < m.shape[0] and m[j + d, i:i + w].all(): d += 1
            m[j:j + d, i:i + w] = False
            out.append((i, j, w, d)); i += w
    return out

lines = ["# Generated by gen_coast.py - rounded coast, 4 smooth ramp tiers, wading shallows.",
         "SKYVOXEL_STRUCTURE 1", "NAME Main_Island_Beach_Transition"]
n = 0
def add(name, mat, x, y, z, w, h, d, solid):
    global n; n += 1
    lines.append(f"CUBOID {name} {mat} {x:.3f} {y:.3f} {z:.3f} {w:.3f} {h:.3f} {d:.3f} {'true' if solid else 'false'}")

for i, (maxd, mat, top, solid) in enumerate(BANDS):
    for ix, iz, w, d in rects(band == i):
        h = top - BOTTOM
        add(f"beach_b{i}_{ix}_{iz}", mat, x0 + (ix + w / 2) * CELL, BOTTOM + h / 2,
            z0 + (iz + d / 2) * CELL, w * CELL, h, d * CELL, solid)

# visual-only shallow-water tint + foam line on top of the sea plane
sh = (band == len(BANDS) - 1) | ((band >= 2) & (dist > 4.5))
for ix, iz, w, d in rects(sh & (band >= 0)):
    add(f"shallows_{ix}_{iz}", "shallow_water", x0 + (ix + w / 2) * CELL, SEA_TOP,
        z0 + (iz + d / 2) * CELL, w * CELL, 0.025, d * CELL, False)
foam = (band >= 0) & (dist > FOAM_AT) & (dist <= FOAM_AT + 1.0)
for ix, iz, w, d in rects(foam):
    add(f"foam_{ix}_{iz}", "foam", x0 + (ix + w / 2) * CELL, SEA_TOP + .005,
        z0 + (iz + d / 2) * CELL, w * CELL, 0.025, d * CELL, False)

# grass edge that got shaved by the rounding: VISUAL-ONLY sand cap (collision stays the flat
# foundation top, so there is no lip to catch the player)
shaved = land & ~grass
for ix, iz, w, d in rects(shaved):
    add(f"shore_cap_{ix}_{iz}", "sand", x0 + (ix + w / 2) * CELL, .015,
        z0 + (iz + d / 2) * CELL, w * CELL, 0.03, d * CELL, False)

BEACH.write_text("\n".join(lines) + "\n")

# 4) plaza fixes: remove rocks, wooden docks flush with the sand
if not (S / "plaza.vstruct.bak").exists():
    shutil.copy(PLAZA, S / "plaza.vstruct.bak")
out, dropped = [], 0
for ln in txt.splitlines():
    if re.match(r"CUBOID rock_\d+ ", ln): dropped += 1; continue
    ln = re.sub(r"^(CUBOID dock_\w+_deck) stone_dark (\S+) -0\.15 ", r"\1 wood_light \2 -0.11 ", ln)
    out.append(ln)
PLAZA.write_text("\n".join(out) + "\n")
print(f"beach cuboids: {n} | rocks removed: {dropped} | root: {ROOT}")
